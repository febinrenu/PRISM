"use client";

import * as React from "react";
import * as Popover from "@radix-ui/react-popover";
import Link from "next/link";
import { cn } from "@/lib/utils";
import { n, pn, type Source } from "./data";

const REPO = "https://github.com/febinrenu/PRISM/blob/main/";

/** A small marker after a number: where it comes from, on click or focus. */
export function SourceRef({ source, label }: { source: Source; label?: string }) {
  const entries = Object.entries(source).filter(([k]) => k !== "inspect" && k !== "route");
  return (
    <Popover.Root>
      <Popover.Trigger
        className="relative -top-[0.55em] ml-0.5 inline-flex h-[18px] min-w-[18px] items-center justify-center rounded-[3px] border border-current px-0.5 align-baseline font-mono text-micro leading-none opacity-50 transition-opacity hover:opacity-100 focus-visible:opacity-100"
        aria-label={`Source${label ? ` for ${label}` : ""}`}
      >
        <span aria-hidden>↗</span>
      </Popover.Trigger>
      <Popover.Portal>
        <Popover.Content
          side="top"
          sideOffset={8}
          collisionPadding={16}
          className="z-overlay max-w-[min(360px,calc(100vw-32px))] rounded-md border border-border-light bg-bg-elevated p-3.5 text-left font-sans text-[13px] leading-relaxed text-text-secondary shadow-lift"
        >
          <div className="mb-1.5 font-mono text-micro uppercase tracking-[0.14em] text-text-dim">Source</div>
          <dl className="space-y-1">
            {entries.map(([k, v]) => (
              <div key={k} className="grid grid-cols-[64px_1fr] gap-2">
                <dt className="text-text-dim">{k}</dt>
                <dd className="break-all font-mono text-[12px] text-text-primary">
                  {k === "file" && v && !v.includes("*") ? (
                    <a href={REPO + v} target="_blank" rel="noopener noreferrer" className="underline decoration-border-light underline-offset-2 hover:decoration-signal">
                      {v}
                    </a>
                  ) : (
                    v
                  )}
                </dd>
              </div>
            ))}
          </dl>
          {source.inspect && (
            <Link href={source.inspect} className="mt-3 inline-block text-[13px] text-signal underline underline-offset-4">
              Inspect this run in the research view
            </Link>
          )}
          <p className="mt-2.5 text-[12px] text-text-dim">
            Generated by <code className="font-mono">python -m cli story-export</code> from results in the repository.
          </p>
          <Popover.Arrow className="fill-bg-elevated" />
        </Popover.Content>
      </Popover.Portal>
    </Popover.Root>
  );
}

/** A number the paper prints, with its source marker. */
export function Num({ k, suffix, className }: { k: string; suffix?: string; className?: string }) {
  const e = n(k);
  return (
    <span className={cn("tabular whitespace-nowrap", className)}>
      <span data-count={e.value}>{e.value}</span>
      {suffix}
      <SourceRef source={e.source} label={k} />
    </span>
  );
}

/** A number from the demo document's pipeline run, with its source marker. */
export function PNum({ k, suffix, className }: { k: string; suffix?: string; className?: string }) {
  const e = pn(k);
  return (
    <span className={cn("tabular whitespace-nowrap", className)}>
      <span data-count={e.value}>{e.value}</span>
      {suffix}
      <SourceRef source={e.source} label={k} />
    </span>
  );
}

/** A value computed from the snapshot, with its source marker. */
export function Val({ children, source, className }: { children: React.ReactNode; source: Source; className?: string }) {
  return (
    <span className={cn("tabular whitespace-nowrap", className)}>
      {children}
      <SourceRef source={source} />
    </span>
  );
}

/**
 * One act: a tall section whose inner panel sticks to the viewport while the
 * reader scrolls through it. `length` is the scroll length in viewport heights.
 */
export function Act({
  id,
  index,
  length,
  label,
  className,
  panelClassName,
  children,
}: {
  id: string;
  index: number;
  length: number;
  label: string;
  className?: string;
  panelClassName?: string;
  children: React.ReactNode;
}) {
  return (
    <section
      id={id}
      data-act={index}
      aria-label={label}
      className={cn("act relative", className)}
      style={{ ["--act-len" as string]: `${length * 100}dvh` }}
    >
      <div className={cn("act-panel sticky top-0 h-dvh w-full overflow-hidden", panelClassName)}>{children}</div>
    </section>
  );
}

/** Reveals when the act's progress passes `at` (0..1). */
export function Step({
  at,
  as = "div",
  className,
  children,
  ...rest
}: {
  at: number;
  as?: keyof JSX.IntrinsicElements;
  className?: string;
  children: React.ReactNode;
} & React.HTMLAttributes<HTMLElement>) {
  const Tag = as as React.ElementType;
  return (
    <Tag data-at={at} className={className} {...rest}>
      {children}
    </Tag>
  );
}

export function Kicker({ numeral, children }: { numeral: string; children: React.ReactNode }) {
  return (
    <div className="mb-5 flex items-center gap-3 font-mono text-micro uppercase tracking-[0.2em] text-text-muted">
      <span className="text-signal">{numeral}</span>
      <span className="h-px w-8 bg-border-light" aria-hidden />
      <span>{children}</span>
    </div>
  );
}
