"""Marks for tests that read the parsed statutes.

The parsed texts (`ast.json`) are generated by `python -m cli ingest` and `python -m cli parse`
and are not committed, so a fresh clone (and CI) skips these tests instead of failing them.
"""
import pytest

from pipeline.statute.corpus import CORPUS_DIR

_NEEDED = [CORPUS_DIR / "ITA2025" / "amended_fa2026" / "ast.json", CORPUS_DIR / "DPDP2023" / "enacted" / "ast.json"]

needs_parsed_corpus = pytest.mark.skipif(
    not all(p.exists() for p in _NEEDED),
    reason="the statute corpus is not parsed (python -m cli ingest && python -m cli parse)")
